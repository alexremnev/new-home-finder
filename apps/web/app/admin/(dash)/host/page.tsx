import { Suspense } from "react";

import { Panel, PanelWait } from "../panel";
import { DEFAULT_SPAN, spanFrom } from "../span";
import { CpuChart, HostTiles, RamChart } from "./bodies";

export const dynamic = "force-dynamic";

// The machine the worker runs on.
export default async function HostPage({
  searchParams,
}: {
  searchParams: Promise<Record<string, string | undefined>>;
}) {
  const params = await searchParams;
  const span = spanFrom(params.w ?? DEFAULT_SPAN).key;

  return (
    <>
      <div className="dash-head">
        <h1>Host</h1>
      </div>

      <Panel
        wide
        title="The machine"
        why="Процессоры, память и диск того самого сервера, на котором крутится воркер — 2 vCPU, 4 ГБ, 40 ГБ, и на нём больше ничего нет: Postgres живёт в Supabase, веб на Vercel. Цифры берутся не от агента мониторинга, а из журнала прогонов: каждый прогон при завершении дописывает один снимок бокса в свои counters, и «сейчас» здесь означает «снимок самого свежего прогона». Так сделано потому, что node exporter на этой машине сам потребовал бы больше памяти, чем измеряемое, а firewall на ней сознательно не пускает внутрь ничего. Цена честная и её стоит назвать: разрешение — один снимок на прогон, поэтому всплеск между двумя прогонами сюда не попадает. Днём читатели ходят каждые 6–12 минут, этого хватает на вопрос «хватало ли ему памяти сегодня днём» и не хватает ни на какой профайлинг. Поле, которое не удалось прочитать, отсутствует, а не равно нулю: прогон со старого кода или хост без /proc не должен считаться снимком, показавшим ноль свободной памяти."
      >
        <Suspense fallback={<PanelWait />}>
          <HostTiles span={span} />
        </Suspense>
      </Panel>

      <div className="dash-row dash-row-wide">
        <Panel
          title="CPU over time"
          why="Тот же load average, что и в плитке выше, но как линия: делённый на число процессоров, так что 100% — это один готовый к выполнению процесс на vCPU, а не «бокс занят». Плитка отвечает на вопрос «хватало ли ему» и на этом останавливается; как только ответ «нет», следующий вопрос — «когда», и пик на него не отвечает. 1.9 на двух ядрах — это одна авария, если это всплеск в 03:00, где сошлись два обхода, и совсем другая, если это полка с полудня. В каждом ведре показан худший снимок, а не средний: бокс, которому не хватило в 14:00 и который отдышался, в среднем выглядит здоровым, и среднее — единственная форма, по которой беду не прочитать. Пунктир на 100%: выше него работы, готовой выполняться, больше, чем процессоров, и на скрейпе, обязанном уложиться в свой таймер, это превращается в опоздавший алерт. Разрыв в линии — это ведро, в которое не попал ни один прогон, а не ноль: ночью таймеры разнесены на час, и линия, падающая там на пол, читалась бы как «нагрузки не было», хотя её просто никто не мерил."
        >
          <Suspense fallback={<PanelWait />}>
            <CpuChart span={span} />
          </Suspense>
        </Panel>

        <Panel
          title="RAM over time"
          why="Занятая память как доля от всех 4 ГБ — дополнение к тому MemAvailable, который печатает плитка. Перевёрнуто сознательно: оба графика должны расти, когда боксу плохо, иначе один падающий и один растущий означают одно и то же, и это читают неправильно ровно один раз, после чего перестают читать. В ведре — худший снимок, то есть минимум available: именно он важнее текущего значения, потому что в последнем снимке бокс, переживший нехватку в 14:00, выглядит здоровым. Пунктир стоит там, где оставшегося перестаёт хватать на те 2 ГБ запаса, которые бокс должен держать свободными (MEMORY_FLOOR): выше него у него уже нет места на всплеск. Линия и порог считаются из одного и того же снимка, что и цвет плитки (health.ts), так что разойтись они не могут. Разрыв — ведро без прогонов; ноль здесь означал бы «свободной памяти нет», то есть обратное истине."
        >
          <Suspense fallback={<PanelWait />}>
            <RamChart span={span} />
          </Suspense>
        </Panel>
      </div>
    </>
  );
}
